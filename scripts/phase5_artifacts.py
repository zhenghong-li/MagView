"""Regenerate artifacts/phase5/: minimal-cell table, sample handoffs, cell renders, GUI.

    .venv/bin/python scripts/phase5_artifacts.py [--no-gui]

The scenarios are the ones verified in tests/test_magcell_handoff.py (imported from there).
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"
OUT = ROOT / "artifacts" / "phase5"
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "tests"))
from render_gallery import contact_sheet  # noqa: E402

RENDER = {"square Neel -> sqrt2 x sqrt2", "NiO AFM-II (rhombohedral)",
          "La2CuO4 A-type (conventional cell)", "Cs3V9Te13 AFM stacking -> 1x1x2",
          "honeycomb zigzag", "triangular 120 deg (non-collinear)"}


def load(name):
    from magview.core.structure import CrystalStructure

    return CrystalStructure.from_file(DATA / f"{name}.cif")


def slug(s: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in s).strip("_").lower()[:48]


def render_cell(cell, path: Path, title: str, appearance) -> None:
    from magview.core.graph import neighbor_graph
    from magview.core.magcell import as_structure
    from magview.core.structure import CrystalStructure
    from magview.render.arrows import ArrowStyle
    from magview.render.model import build_scene_model
    from magview.render.offscreen import make_plotter
    from magview.render.scene import StructureScene

    crystal = CrystalStructure.from_pymatgen(as_structure(cell))
    model = build_scene_model(crystal, appearance, site_moments=cell.moments, moment_view=True)
    mags = np.linalg.norm(cell.moments, axis=1)
    g = neighbor_graph(cell.lattice, cell.frac_coords, np.nonzero(mags > 0)[0])
    t = appearance.theme
    plotter = make_plotter((620, 560))
    plotter.enable_anti_aliasing("ssaa")
    scene = StructureScene(plotter, t)
    scale = round(0.8 * g.d_nn / mags.max(), 2) if g.d_nn > 0 else 1.0
    scene.arrow_style = ArrowStyle(scale, t.arrow_shaft_radius, t.arrow_head_radius_ratio,
                                   t.arrow_head_length_ratio, True, t.arrow_resolution)
    scene.color_mode = "sign" if np.allclose(cell.moments[:, :2], 0) else "direction"
    scene.set_model(model)
    plotter.add_text(title, position="upper_left", font_size=10, color="black")
    plotter.render()
    plotter.screenshot(str(path))
    plotter.close()
    print("wrote", path.relative_to(ROOT))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-gui", action="store_true")
    args = ap.parse_args()
    from magview.core.magcell import minimal_magnetic_cell
    from magview.io.handoff import build_handoff, save_handoff
    from magview.render.offscreen import configure_offscreen
    from magview.style.appearance import Appearance
    from test_magcell_handoff import CASES

    configure_offscreen()
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "handoffs").mkdir(parents=True)
    appearance = Appearance.load()
    items = []
    rows = ["# Phase 5: minimal magnetic cells", "",
            "Generated by `scripts/phase5_artifacts.py` from the scenarios verified in "
            "`tests/test_magcell_handoff.py`. 'x prim' = magnetic cell volume / chemical "
            "primitive cell volume. MSG = spglib magnetic space group (UNI number, type); its "
            "primitive volume matches the computed cell in every case.", "",
            "| Scenario | x prim | vs input cell | Sites | Unfolding | MSG | Why |",
            "|---|---|---|---|---|---|---|"]
    for name, (build, mult, _) in CASES.items():
        doc = build(load)
        cell = minimal_magnetic_cell(doc)
        handoff = build_handoff(doc, cell)
        save_handoff(handoff, OUT / "handoffs" / f"{slug(name)}.json")
        msg = cell.msg or {}
        why = " ".join(cell.explanation[1:] if len(cell.explanation) > 1 else cell.explanation)
        rows.append(f"| {name} | {cell.multiplicity} | {cell.describe_matrix()} | {len(cell.species)} | "
                    f"{handoff['requires_unfolding']} | {msg.get('uni_number')} (type {msg.get('msg_type')}) "
                    f"| {why} |")
        if name in RENDER:
            p = OUT / f"cell_{slug(name)}.png"
            render_cell(cell, p, f"{name}: {cell.multiplicity} x primitive ({cell.describe_matrix()})",
                        appearance)
            items.append((p, name))
    (OUT / "minimal_cells.md").write_text("\n".join(rows) + "\n")
    print("wrote", (OUT / "minimal_cells.md").relative_to(ROOT))

    ok = True
    if not args.no_gui and shutil.which("xvfb-run"):
        for name in ("Cs3V9Te13_300K", "NiO"):
            out = OUT / f"gui_{name.split('_')[0].lower()}"
            proc = subprocess.run(["xvfb-run", "-a", "-s", "-screen 0 1600x1000x24", sys.executable,
                                   "-m", "magview.gui.selftest", str(DATA / f"{name}.cif"),
                                   "--out", str(out)], capture_output=True, text=True, timeout=900)
            print(proc.stdout.strip())
            results = json.loads((out / "selftest.json").read_text())
            ok &= proc.returncode == 0 and all(r["ok"] for r in results)
            shutil.rmtree(out / "autosave", ignore_errors=True)
            jobs = sorted((out / "agentdft_jobs").glob("*/job.json"))
            if jobs:
                shutil.copy(jobs[0], out / "mock_agentdft_job.json")
            shutil.rmtree(out / "agentdft_jobs", ignore_errors=True)
            for png in out.glob("*.png"):
                if not png.name.startswith(("13_", "14_")):
                    png.unlink()
            for png in sorted(out.glob("*.png")):
                items.append((png, f"GUI {png.stem} - {name.split('_')[0]}"))
    contact_sheet(items, OUT / "contact_sheet.png", cols=3, cell_w=620)
    print("wrote", (OUT / "contact_sheet.png").relative_to(ROOT))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
