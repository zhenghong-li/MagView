"""Regenerate artifacts/phase4/: stacked configurations in 3D, frustration cases, GUI.

    .venv/bin/python scripts/phase4_artifacts.py [--no-gui]
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"
OUT = ROOT / "artifacts" / "phase4"
sys.path.insert(0, str(ROOT / "scripts"))
from phase2_artifacts import render_doc  # noqa: E402
from phase3_artifacts import new_doc  # noqa: E402
from render_gallery import contact_sheet  # noqa: E402


def stack(doc, inplane: str, stacking: str):
    """Set layer 0 to an in-plane pattern, then stack all layers; returns (ok, message)."""
    from magview.core.layers import decompose
    from magview.core.patterns import match_layer
    from magview.core.stacking import fm_reference, stacking_library

    dec = decompose(doc.canvas.structure, np.nonzero(doc.canvas_magnetic)[0],
                    doc.crystal.lattice_matrix, "c")
    group = list(dec.layers)
    L0 = group[0]
    if inplane == "fm":
        base = np.ones(len(L0.sites), int)
    else:
        k = int(np.nonzero(L0.lattice.bond_class == 0)[0][0])
        i, j = int(L0.graph.i[k]), int(L0.graph.j[k])
        pins = {i: 1, j: -1} if inplane in ("neel",) else {i: 1, j: 1}
        res = match_layer(L0, pins)
        base = next(c for c in res.candidates if c.pattern.key.startswith(inplane)).signs
    ref = fm_reference(doc.canvas.structure, group, dec.normal, dec.period, base)
    if not ref.ok:
        return False, ref.reason
    pat = next(p for p, inv in stacking_library(len(group)) if p.key == stacking)
    sites = np.concatenate([G.sites for G in group])
    doc.apply_completion(sites, np.concatenate([f * r for f, r in zip(pat.flips, ref.signs)]),
                         f"{inplane} + {pat.label}")
    return True, f"{len(group)} layers: {inplane} in plane, {pat.label}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-gui", action="store_true")
    args = ap.parse_args()
    from magview.render.offscreen import configure_offscreen
    from magview.style.appearance import Appearance

    configure_offscreen()
    if OUT.exists():
        for p in OUT.glob("*.png"):
            p.unlink()
    OUT.mkdir(parents=True, exist_ok=True)
    appearance = Appearance.load()
    items = []
    lines = ["# Phase 4: stacking outcomes", "", "Generated by `scripts/phase4_artifacts.py`.", "",
             "| Structure | In-plane | Stacking | Result |", "|---|---|---|---|"]
    cases = [("toy_square_CuO2", "neel", "fm", "C-type (Neel planes, FM stacked)"),
             ("toy_square_CuO2", "neel", "afm", "G-type (Neel planes, AFM stacked)"),
             ("FeSe", "stripe", "afm", "FeSe: stripe planes, AFM stacked"),
             ("La2CuO4", "fm", "afm", "La2CuO4: FM planes, AFM stacked (A-type)"),
             ("Cs3V9Te13_300K", "fm", "afm", "Cs3V9Te13: FM V planes, AFM stacked"),
             ("La2CuO4", "neel", "fm", "La2CuO4: Neel planes (frustrated)"),
             ("NiO", "neel", "fm", "NiO (001): Neel planes (frustrated)")]
    for name, inplane, stacking, title in cases:
        doc = new_doc(name)
        ok, msg = stack(doc, inplane, stacking)
        lines.append(f"| {doc.crystal.formula} | {inplane} | {stacking} | "
                     f"{'applied: ' + msg if ok else 'not offered: ' + msg} |")
        if not ok:
            print(f"{title}: {msg}")
            continue
        path = OUT / f"stack_{name}_{inplane}_{stacking}.png"
        render_doc(doc, path, appearance, title=title, scale="auto")
        items.append((path, title))
    (OUT / "stacking_outcomes.md").write_text("\n".join(lines) + "\n")
    print("wrote", (OUT / "stacking_outcomes.md").relative_to(ROOT))

    ok = True
    if not args.no_gui and shutil.which("xvfb-run"):
        out = OUT / "gui_nio"
        if out.exists():
            shutil.rmtree(out)
        proc = subprocess.run(["xvfb-run", "-a", "-s", "-screen 0 1600x1000x24", sys.executable, "-m",
                               "magview.gui.selftest", str(DATA / "NiO.cif"), "--out", str(out)],
                              capture_output=True, text=True, timeout=600)
        print(proc.stdout.strip())
        shutil.rmtree(out / "autosave", ignore_errors=True)
        results = json.loads((out / "selftest.json").read_text())
        ok = proc.returncode == 0 and all(r["ok"] for r in results)
        for png in out.glob("*.png"):
            if not png.name.startswith("12_"):
                png.unlink()
        items.append((out / "12_stacking_suggestion.png", "GUI: stacking suggestion (NiO)"))
    contact_sheet(items, OUT / "contact_sheet.png", cols=3, cell_w=620)
    print("wrote", (OUT / "contact_sheet.png").relative_to(ROOT))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
