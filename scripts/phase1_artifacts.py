"""Regenerate artifacts/phase1/: canvas, gesture renders, suggestion tables, GUI self-tests.

    .venv/bin/python scripts/phase1_artifacts.py [--no-gui]
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "tests" / "data"
OUT = ROOT / "artifacts" / "phase1"
SIZE = (1100, 850)

sys.path.insert(0, str(ROOT / "scripts"))
from render_gallery import contact_sheet  # noqa: E402


def canvas_scene(name: str, appearance):
    from magview.core.document import MagDocument
    from magview.core.structure import CrystalStructure
    from magview.render.model import build_scene_model, subcell_edges
    from magview.render.offscreen import make_plotter
    from magview.render.scene import StructureScene

    crystal = CrystalStructure.from_file(DATA / f"{name}.cif")
    doc = MagDocument.new(crystal)
    plotter = make_plotter(SIZE)
    plotter.enable_anti_aliasing("ssaa")
    scene = StructureScene(plotter, appearance.theme)
    model = build_scene_model(doc.canvas.structure, appearance,
                              grid_edges=subcell_edges(crystal.lattice_matrix, doc.canvas.matrix))
    scene.set_model(model)
    return doc, plotter, scene


def save(plotter, path: Path) -> Path:
    plotter.render()
    plotter.screenshot(str(path))
    print("wrote", path.relative_to(ROOT))
    return path


def gesture_frames(name: str, appearance, items: list) -> None:
    """Drive the real state machine + picking offscreen and render each stage."""
    from magview.core import interaction as ia
    from magview.core.selection import apply_selection
    from magview.render.overlay import BoxOverlay
    from magview.render.picking import atoms_in_box, pick_atom, project_to_display

    doc, plotter, scene = canvas_scene(name, appearance)
    ren, model = plotter.renderer, scene.model
    tag = name.split("_")[0].lower()
    items.append((save(plotter, OUT / f"{tag}_canvas_2x2x2.png"),
                  f"{doc.crystal.formula}: editing canvas 2x2x2 (grid = input cells)"))

    machine = ia.InteractionMachine()
    sel: frozenset[int] = frozenset()

    def apply(actions):
        nonlocal sel
        for a in actions:
            if isinstance(a, ia.Select):
                sel = apply_selection(sel, a.sites, a.op)
            elif isinstance(a, ia.BoxFinish):
                box.hide()
                inside = {int(model.atoms.parent[i]) for i in atoms_in_box(ren, model, a.x0, a.y0, a.x1, a.y1)}
                sel = apply_selection(sel, inside, a.op)
            elif isinstance(a, ia.BoxArmed):
                box.armed(a.x, a.y)
            elif isinstance(a, ia.BoxUpdate):
                box.update(a.x0, a.y0, a.x1, a.y1)
        idx = np.nonzero(np.isin(model.atoms.parent, sorted(sel)))[0]
        scene.set_selection(idx)

    box = BoxOverlay(ren)
    # Click the front-most magnetic atom: its parent and all its periodic images light up.
    xy = project_to_display(ren, model.atoms.cart)
    cam = plotter.camera
    d = np.array(cam.position) - np.array(cam.focal_point)
    mag = np.nonzero(doc.canvas_magnetic[model.atoms.parent] | np.isin(
        np.array(model.atom_symbols), ["V", "Ni", "Fe", "Cu"]))[0]
    front = mag[np.argmax(model.atoms.cart[mag] @ d)]
    x, y = xy[front]
    hit = pick_atom(ren, model, x, y)
    apply(machine.handle(ia.Press(x, y, 0.0, int(model.atoms.parent[hit]))))
    apply(machine.handle(ia.Release(x, y, 0.1)))
    items.append((save(plotter, OUT / f"{tag}_click.png"),
                  f"click: site {sorted(sel)} + its images (halo)"))

    w, h = ren.GetSize()
    x0, y0, x1, y1 = 0.36 * w, 0.30 * h, 0.66 * w, 0.62 * h
    apply(machine.handle(ia.Press(x0, y0, 1.0)))
    apply(machine.handle(ia.Tick(1.4)))  # long press -> box armed
    apply(machine.handle(ia.Move(x1, y1, 1.5, ia.Mods(shift=True))))
    items.append((save(plotter, OUT / f"{tag}_box_dragging.png"),
                  "long-press + drag: rubber band (Shift = add)"))
    apply(machine.handle(ia.Release(x1, y1, 1.6, ia.Mods(shift=True))))
    items.append((save(plotter, OUT / f"{tag}_box_result.png"),
                  f"box result: {len(sel)} sites selected"))
    plotter.close()


def suggestion_tables() -> Path:
    from pymatgen.core import Lattice, Structure

    from magview.core.structure import CrystalStructure
    from magview.core.suggest import ElementRuleSuggester

    s = ElementRuleSuggester()
    lines = ["# Phase 1: magnetic-site suggestions (element-rules-v1)", "",
             "Generated by `scripts/phase1_artifacts.py`. One row per symmetry orbit. "
             "Excluded rows are shown with their reason; nothing is dropped silently.", ""]
    extra = {
        "SrTiO3 (extra)": Structure(Lattice.cubic(3.905), ["Sr", "Ti", "O", "O", "O"],
                                    [[0, 0, 0], [.5, .5, .5], [.5, .5, 0], [.5, 0, .5], [0, .5, .5]]),
        "GdN (extra)": Structure(Lattice.cubic(4.97), ["Gd", "N"], [[0, 0, 0], [.5, .5, .5]]),
        "RuO2 (extra)": Structure(Lattice.tetragonal(4.49, 3.11), ["Ru", "Ru", "O", "O", "O", "O"],
                                  [[0, 0, 0], [.5, .5, .5], [.3, .3, 0], [.7, .7, 0], [.8, .2, .5],
                                   [.2, .8, .5]]),
    }
    crystals = {p.stem: CrystalStructure.from_file(p) for p in sorted(DATA.glob("*.cif"))}
    crystals.update({k: CrystalStructure.from_pymatgen(v) for k, v in extra.items()})
    for name, c in crystals.items():
        r = s.suggest(c)
        oxi = ", ".join(f"{k} {v:+.3g}" for k, v in r.oxidation_states.items()) if r.oxidation_states else "none"
        lines += [f"## {name} ({c.formula}, {c.symmetry.international})", "",
                  f"Oxidation-state guess: {oxi}", ""]
        lines += [r.as_markdown() if r.items else "_No magnetic candidates._", ""]
    path = OUT / "suggestions.md"
    path.write_text("\n".join(lines))
    print("wrote", path.relative_to(ROOT))
    return path


def gui_selftest(name: str, items: list) -> bool:
    if shutil.which("xvfb-run") is None:
        print("skip GUI self-test: xvfb-run missing")
        return False
    out = OUT / f"gui_{name.split('_')[0].lower()}"
    if out.exists():
        shutil.rmtree(out)
    proc = subprocess.run(["xvfb-run", "-a", "-s", "-screen 0 1600x1000x24", sys.executable, "-m",
                           "magview.gui.selftest", str(DATA / f"{name}.cif"), "--out", str(out)],
                          capture_output=True, text=True, timeout=300)
    print(proc.stdout.strip())
    results = json.loads((out / "selftest.json").read_text())
    for png, title in (("02_box_dragging", "GUI: long-press box (real Qt events)"),
                       ("04_accepted_moment_view", "GUI: suggestions accepted, moment view")):
        items.append((out / f"{png}.png", f"{title} - {name.split('_')[0]}"))
    return proc.returncode == 0 and all(r["ok"] for r in results)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-gui", action="store_true")
    args = ap.parse_args()

    from magview.render.offscreen import configure_offscreen
    from magview.style.appearance import Appearance

    configure_offscreen()
    OUT.mkdir(parents=True, exist_ok=True)
    appearance = Appearance.load()
    items: list = []
    for name in ("NiO", "Cs3V9Te13_300K"):
        gesture_frames(name, appearance, items)
    suggestion_tables()
    ok = True
    if not args.no_gui:
        for name in ("NiO", "Cs3V9Te13_300K"):
            ok &= gui_selftest(name, items)
    contact_sheet(items, OUT / "contact_sheet.png", cols=4, cell_w=520)
    print("wrote", (OUT / "contact_sheet.png").relative_to(ROOT))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
